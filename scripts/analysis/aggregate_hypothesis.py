"""Aggregate hypothesis cross-validation results into stats, paired tests, LaTeX tables, and publication-ready boxplots.

Supports H1, H2, H3, H4, and generic fold results generated by the training pipeline.

Features:
  - Formal, readable label mapping for thesis and paper publication.
  - Paired parametric (paired t-test, Cohen's d) and non-parametric (Wilcoxon signed-rank) hypothesis testing.
  - High-resolution (300 DPI) raster PNG and vector PDF boxplots with jittered fold points and statistical annotations.
  - Multi-format exports: CSV, Markdown report, and LaTeX table snippets.

Examples:
    python scripts/analysis/aggregate_hypothesis.py \\
        --fold-results ../results_from_apl19/h1_effb0_32fold_8gpu/fold_results.csv \\
        --hypothesis h1 \\
        --output-dir results/h1_effb0_32fold

    python scripts/analysis/aggregate_hypothesis.py \\
        --fold-results ../results_from_apl19/h4_effb0_reuseSmall_res34_trainLarge_32fold_8gpu/fold_results.csv \\
        --configs-dir ../results_from_apl19/h4_effb0_reuseSmall_res34_trainLarge_32fold_8gpu/configs \\
        --hypothesis h4 \\
        --output-dir results/h4_backbones
"""

