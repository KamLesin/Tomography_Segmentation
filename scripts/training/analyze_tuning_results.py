"""
Hyperparameter tuning results analyzer and cross-machine transfer helper.

This script:
1. Aggregates results from hyperparameter tuning grid search
2. Ranks configurations by CV score
3. Provides transfer instructions between different GPU setups
4. Exports best configurations for production use

Usage:
    # Analyze tuning results
    python scripts/training/analyze_tuning_results.py \
        --tuning-dir runs/hyperparameter_tuning

    # Export best config for production
    python scripts/training/analyze_tuning_results.py \
        --tuning-dir runs/hyperparameter_tuning \
        --export-best \
        --target-config config/training/multiphase_production.yaml
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any, Dict, List, Optional
import statistics

import pandas as pd
import numpy as np
import yaml


def load_yaml(path: Path) -> Dict[str, Any]:
    """Load YAML configuration file."""
    with open(path, "r", encoding="utf-8") as f:
        return yaml.safe_load(f)


def save_yaml(data: Dict[str, Any], path: Path) -> None:
    """Save configuration to YAML file."""
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        yaml.dump(data, f, default_flow_style=False, sort_keys=False)


def collect_fold_results(config_dir: Path) -> Dict[str, Any]:
    """
    Collect metrics from all folds in a configuration run.
    
    Returns:
        dict with aggregated metrics: mean_dice, std_dice, mean_hd95, etc.
    """
    cv_results_dir = config_dir / "cv_results"
    
    if not cv_results_dir.exists():
        return {
            "status": "no_results",
            "mean_dice": None,
            "std_dice": None,
            "fold_count": 0,
        }
    
    fold_metrics = []
    
    # Collect from each fold
    for fold_dir in sorted(cv_results_dir.glob("fold_*")):
        # Look for metrics.json (should be generated by train_cv.py)
        metrics_file = fold_dir / "metrics.json"
        if metrics_file.exists():
            try:
                with open(metrics_file, "r") as f:
                    fold_data = json.load(f)
                
                # Extract validation Dice (or best.pt evaluation)
                val_dice = fold_data.get("val_dice", fold_data.get("best_dice_val"))
                if val_dice:
                    fold_metrics.append(val_dice)
            except Exception as e:
                print(f"  Warning: Could not load {metrics_file}: {e}")
    
    if fold_metrics:
        return {
            "status": "complete",
            "mean_dice": statistics.mean(fold_metrics),
            "std_dice": statistics.stdev(fold_metrics) if len(fold_metrics) > 1 else 0.0,
            "fold_count": len(fold_metrics),
            "fold_scores": fold_metrics,
        }
    else:
        return {
            "status": "partial",
            "mean_dice": None,
            "std_dice": None,
            "fold_count": 0,
        }


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(
        description="Analyze hyperparameter tuning results and prepare transfer"
    )
    p.add_argument(
        "--tuning-dir",
        type=Path,
        required=True,
        help="Root directory of hyperparameter tuning run",
    )
    p.add_argument(
        "--export-best",
        action="store_true",
        help="Export best config to production file",
    )
    p.add_argument(
        "--target-config",
        type=Path,
        default=Path("config/training/multiphase_production.yaml"),
        help="Output path for best configuration",
    )
    p.add_argument(
        "--source-gpu-setup",
        type=str,
        default="4x_RTX_Quadro_5000_16GB",
        help="GPU setup description for source machine",
    )
    p.add_argument(
        "--target-gpu-setup",
        type=str,
        default="8x_RTX_Quadro_6000_24GB",
        help="GPU setup description for target machine",
    )
    return p.parse_args()


def scale_config_for_gpus(
    config: Dict[str, Any],
    source_vram_gb: int,
    target_vram_gb: int,
    source_num_gpus: int,
    target_num_gpus: int,
) -> Dict[str, Any]:
    """
    Scale hyperparameters when transferring between different GPU setups.
    
    Scaling principles:
    - batch_size scales with available VRAM per GPU
    - learning_rate may need adjustment (smaller LR for larger batch sizes)
    - num_workers scales with available compute
    """
    import copy
    scaled = copy.deepcopy(config)
    
    # Calculate VRAM scaling factor
    source_total_vram = source_vram_gb * source_num_gpus
    target_total_vram = target_vram_gb * target_num_gpus
    vram_ratio = target_total_vram / source_total_vram
    
    # Scale batch size proportionally to VRAM
    # Note: batch_size is per GPU, so we scale the per-GPU allocation
    if "train" in scaled and "batch_size" in scaled["train"]:
        old_batch = scaled["train"]["batch_size"]
        new_batch = max(1, int(old_batch * (target_vram_gb / source_vram_gb)))
        scaled["train"]["batch_size"] = new_batch
        print(f"  Batch size: {old_batch} -> {new_batch} (VRAM: {source_vram_gb}GB -> {target_vram_gb}GB per GPU)")
    
    # Adjust num_workers (fewer workers on smaller systems)
    if "data" in scaled and "num_workers" in scaled["data"]:
        old_workers = scaled["data"].get("num_workers", 4)
        new_workers = max(1, int(old_workers * (target_num_gpus / source_num_gpus)))
        scaled["data"]["num_workers"] = new_workers
        print(f"  Num workers: {old_workers} -> {new_workers} ({source_num_gpus} -> {target_num_gpus} GPUs)")
    
    # Slight LR adjustment for larger batch sizes
    if "train" in scaled and "batch_size" in scaled["train"]:
        new_batch = scaled["train"]["batch_size"]
        old_batch = config["train"].get("batch_size", 16)
        if "lr" in scaled["train"]:
            old_lr = scaled["train"]["lr"]
            # LR scaling: sqrt rule for batch size changes
            lr_scale = np.sqrt(new_batch / old_batch)
            new_lr = old_lr * lr_scale
            scaled["train"]["lr"] = new_lr
            print(f"  Learning rate: {old_lr:.6f} -> {new_lr:.6f} (batch scale factor: {lr_scale:.3f})")
    
    return scaled


def print_transfer_guide(
    source_setup: str,
    target_setup: str,
) -> None:
    """Print guide for transferring tuning results between GPU setups."""
    
    guide = f"""
{'='*80}
HYPERPARAMETER TRANSFER GUIDE
{'='*80}

SOURCE GPU SETUP: {source_setup}
TARGET GPU SETUP: {target_setup}

KEY FINDINGS:

1. DIRECT TRANSFER (Recommended if both setups similar):
   - Hyperparameters like learning_rate, weight_decay are largely GPU-agnostic
   - Skip connections, model architecture remain unchanged
   - Only batch_size needs scaling for VRAM constraints

2. VRAM-DEPENDENT SCALING (When transferring to different GPU):
   - batch_size: scales linearly with available VRAM per GPU
   - attention_max_tokens: may need reduction on smaller GPUs
   - num_workers: scales with number of GPUs
   - learning_rate: slight adjustment based on batch size changes (sqrt rule)

3. PARAMETER PORTABILITY:
   
   ✓ PORTABLE (no changes needed):
   - model.encoder_backbone (network architecture)
   - model.fusion_mode (fusion strategy)
   - train.weight_decay
   - train.dice_weight
   - train.min_lr
   - data.image_size
   - data.hu_window
   - data.context_slices
   
   ⚠ SCALE-DEPENDENT (adjust based on VRAM):
   - train.batch_size
   - train.accumulation_steps
   - model.attention_max_tokens
   - model.full_res_channels
   - data.cache_items
   - data.num_workers
   
   ✗ REVALIDATE (may need tuning on new hardware):
   - train.lr (slight adjustment from sqrt batch scaling)

4. STEP-BY-STEP TRANSFER:
   
   Step 1: Identify best configuration from source setup
   Step 2: Extract configuration YAML
   Step 3: Apply VRAM scaling factors
   Step 4: Run few folds (e.g., 2-4) on target hardware as validation
   Step 5: If Dice scores similar (±2%), use full CV with scaled config
   Step 6: If scores differ significantly, retune learning_rate and batch_size

5. EXPECTED VRAM REQUIREMENT CHANGES:
   
   RTX Quadro 5000 (16GB) → RTX Quadro 6000 (24GB):
   - 24/16 = 1.5x more VRAM available per GPU
   - batch_size can increase by ~1.5x
   - attention_max_tokens can increase by ~1.3x
   - Expect 10-15% training speedup from reduced gradient accumulation

   4 GPUs (Quadro 5000) → 8 GPUs (Quadro 6000):
   - Total VRAM: 64GB → 192GB (3x increase)
   - Can significantly increase batch_size per GPU
   - Can increase accumulation_steps or reduce it
   - Distributed training may show different convergence

6. RECOMMENDED VALIDATION PROTOCOL:
   
   Before full run:
   - Run 2-3 folds with scaled config
   - Compare Dice scores to source setup (should be within ±2%)
   - Check convergence curves (loss trends should be similar)
   - Monitor GPU memory usage
   
   If validation passes:
   - Run full CV (all 32 folds) with high confidence
   - Expected improvement: none (same hyperparameters, just different hardware)
   
   If validation fails (Dice drops >2%):
   - Fine-tune batch_size (try ±20% changes)
   - Adjust learning_rate (try LR schedule changes)
   - Check gradient accumulation steps

{'='*80}
"""
    print(guide)


def main() -> None:
    args = parse_args()
    
    if not args.tuning_dir.exists():
        print(f"Error: Tuning directory not found: {args.tuning_dir}")
        return
    
    print(f"[Analysis] Loading results from: {args.tuning_dir}")
    
    # Load summary
    summary_file = args.tuning_dir / "tuning_summary.json"
    if not summary_file.exists():
        print(f"Warning: Summary file not found: {summary_file}")
        results = []
    else:
        with open(summary_file, "r") as f:
            results = json.load(f)
    
    print(f"[Analysis] Found {len(results)} configurations\n")
    
    # Analyze each configuration
    ranked_configs = []
    for result in results:
        config_name = result["config_name"]
        config_dir = args.tuning_dir / config_name
        
        fold_results = collect_fold_results(config_dir)
        
        ranked_configs.append({
            "config_name": config_name,
            "status": result.get("status", "unknown"),
            "fold_status": fold_results["status"],
            "mean_dice": fold_results.get("mean_dice"),
            "std_dice": fold_results.get("std_dice"),
            "fold_count": fold_results.get("fold_count", 0),
            "config_path": config_dir / "config.yaml",
        })
    
    # Sort by mean Dice (best first)
    ranked_configs.sort(
        key=lambda x: (x["mean_dice"] is not None, x["mean_dice"]),
        reverse=True
    )
    
    # Print ranking table
    print("RANKING BY MEAN VALIDATION DICE\n")
    print(f"{'Rank':<6} {'Config Name':<30} {'Mean Dice':<12} {'Std Dev':<10} {'Folds':<8} {'Status':<10}")
    print("-" * 76)
    
    for idx, config in enumerate(ranked_configs[:20], 1):  # Top 20
        dice_str = f"{config['mean_dice']:.4f}" if config['mean_dice'] else "N/A"
        std_str = f"±{config['std_dice']:.4f}" if config['std_dice'] else "N/A"
        
        print(
            f"{idx:<6} {config['config_name']:<30} {dice_str:<12} {std_str:<10} "
            f"{config['fold_count']:<8} {config['fold_status']:<10}"
        )
    
    print()
    
    # Export best if requested
    if args.export_best and ranked_configs[0]["mean_dice"] is not None:
        best_config = ranked_configs[0]
        source_path = best_config["config_path"]
        
        print(f"\n[Export] Best configuration: {best_config['config_name']}")
        print(f"[Export] Mean Dice: {best_config['mean_dice']:.4f} ± {best_config['std_dice']:.4f}")
        
        # Load best config
        best_yaml = load_yaml(source_path)
        
        # Save as production config
        save_yaml(best_yaml, args.target_config)
        print(f"[Export] Saved to: {args.target_config}")
    
    # Print transfer guide
    print_transfer_guide(args.source_gpu_setup, args.target_gpu_setup)


if __name__ == "__main__":
    main()
